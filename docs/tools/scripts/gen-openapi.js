'use strict';
// Exports the OpenAPI document (api/openapi/spec.js) as docs/w17/openapi.json and openapi.yaml.
// Usage: node scripts/gen-openapi.js
const fs = require('fs');
const path = require('path');
const spec = require('../api/openapi/spec');

const plain = /^[A-Za-z_][A-Za-z0-9_./-]*$/;
const scalar = (v) => {
  if (v === null) return 'null';
  if (typeof v === 'string') return plain.test(v) && !/^(true|false|null|yes|no|on|off|y|n|~)$/i.test(v) ? v : JSON.stringify(v);
  return String(v);
};
function toYaml(v, indent = 0) {
  const pad = '  '.repeat(indent);
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    return v.map((x) => {
      if (x && typeof x === 'object') { const inner = toYaml(x, indent + 1); return `${pad}- ${inner.replace(/^\s+/, '')}`; }
      return `${pad}- ${scalar(x)}`;
    }).join('\n');
  }
  if (v && typeof v === 'object') {
    const keys = Object.keys(v);
    if (!keys.length) return '{}';
    return keys.map((k) => {
      const key = /^[A-Za-z_$][\w$-]*$/.test(k) ? k : JSON.stringify(k);
      const val = v[k];
      if (val && typeof val === 'object' && (Array.isArray(val) ? val.length : Object.keys(val).length)) return `${pad}${key}:\n${toYaml(val, indent + 1)}`;
      return `${pad}${key}: ${val && typeof val === 'object' ? (Array.isArray(val) ? '[]' : '{}') : scalar(val)}`;
    }).join('\n');
  }
  return pad + scalar(v);
}

const out = path.join(__dirname, '..', 'docs', 'w17');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'openapi.json'), JSON.stringify(spec, null, 2) + '\n');
fs.writeFileSync(path.join(out, 'openapi.yaml'), '# Generated by scripts/gen-openapi.js from api/openapi/spec.js. Do not edit by hand.\n' + toYaml(spec) + '\n');
const ops = Object.entries(spec.paths).flatMap(([p, o]) => Object.keys(o).map((m) => `${m.toUpperCase()} ${p}`));
console.log(`openapi.json and openapi.yaml written: ${ops.length} operations, ${Object.keys(spec.components.schemas).length} schemas`);
